-- Offline-first sales: a client-generated UUID is the idempotency key.
-- This migration is additive and safe to apply to an existing project.
alter table public.sales add column if not exists client_sale_id uuid;
create unique index if not exists sales_client_sale_id_key
  on public.sales (client_sale_id) where client_sale_id is not null;

create or replace function public.complete_offline_sale(
  p_client_sale_id uuid,
  p_customer_id uuid,
  p_items jsonb,
  p_payments jsonb,
  p_notes text default null
) returns public.sales language plpgsql security definer set search_path = public as $$
declare v_sale public.sales;
begin
  if p_client_sale_id is null then raise exception 'Client sale id is required'; end if;
  if auth.uid() is null or not (public.has_role('cashier') or public.has_role('director')) then raise exception 'Permission denied'; end if;

  -- Serialise retries for this key. A timeout/retry can therefore never create
  -- two sales or consume stock twice.
  perform pg_advisory_xact_lock(hashtextextended(p_client_sale_id::text, 0));
  select * into v_sale from public.sales where client_sale_id = p_client_sale_id;
  if found then return v_sale; end if;

  select * into v_sale from public.complete_sale(p_customer_id, p_items, p_payments, p_notes);
  update public.sales set client_sale_id = p_client_sale_id where id = v_sale.id returning * into v_sale;
  return v_sale;
end;
$$;

revoke all on function public.complete_offline_sale(uuid, uuid, jsonb, jsonb, text) from public;
grant execute on function public.complete_offline_sale(uuid, uuid, jsonb, jsonb, text) to authenticated;

comment on column public.sales.client_sale_id is 'Stable UUID generated by the offline client; prevents duplicate synchronization.';
